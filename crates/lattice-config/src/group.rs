// Compile-time naming-rule assertions for the built-in groups.
// Verifies the `groups!` macro convention even though these
// groups are hand-written: no built-in group's name ends in
// `-mode`. If we add a `groups!` macro that wraps these
// later, it'll emit the same assertion at the macro call site.

const _: () = {
    assert!(!ends_with_mode_suffix(Editor::NAME));
    assert!(!ends_with_mode_suffix(Display::NAME));
    assert!(!ends_with_mode_suffix(Editing::NAME));
    assert!(!ends_with_mode_suffix(Lsp::NAME));
    assert!(!ends_with_mode_suffix(Completion::NAME));
    assert!(!ends_with_mode_suffix(Picker::NAME));
    assert!(!ends_with_mode_suffix(Filetree::NAME));
    assert!(!ends_with_mode_suffix(Oil::NAME));
    assert!(!ends_with_mode_suffix(Help::NAME));
    assert!(!ends_with_mode_suffix(Appearance::NAME));
    assert!(!ends_with_mode_suffix(Terminal::NAME));
    assert!(!ends_with_mode_suffix(Search::NAME));
    assert!(!ends_with_mode_suffix(Snippet::NAME));
    assert!(!ends_with_mode_suffix(Modeline::NAME));
    assert!(!ends_with_mode_suffix(Diagnostics::NAME));
    assert!(!ends_with_mode_suffix(Window::NAME));
    assert!(!ends_with_mode_suffix(Ai::NAME));
};

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ends_with_mode_suffix_positive() {
        assert!(ends_with_mode_suffix("rust-mode"));
        assert!(ends_with_mode_suffix("lsp-completion-mode"));
        assert!(ends_with_mode_suffix("a-mode"));
        assert!(ends_with_mode_suffix("-mode"));
    }

    #[test]
    fn ends_with_mode_suffix_negative() {
        assert!(!ends_with_mode_suffix("editor"));
        assert!(!ends_with_mode_suffix("lsp"));
        assert!(!ends_with_mode_suffix("mode"));
        assert!(!ends_with_mode_suffix("modal"));
        assert!(!ends_with_mode_suffix(""));
        assert!(!ends_with_mode_suffix("foo"));
    }

    #[test]
    fn builtin_groups_have_distinct_type_ids() {
        // Trivially true (Rust types are unique by path), but
        // pinning the invariant catches any accidental shared
        // alias / re-export collapse.
        let editor = Editor::type_id();
        let display = Display::type_id();
        assert_ne!(editor, display);
    }

    #[test]
    fn linkme_aggregates_builtin_groups() {
        // Walk the slice and confirm every built-in name shows up.
        let names: Vec<_> = GROUP_DECLS.iter().map(|g| g.name).collect();
        for expected in [
            "editor",
            "display",
            "editing",
            "lsp",
            "completion",
            "picker",
            "filetree",
            "oil",
            "help",
            "appearance",
        ] {
            assert!(
                names.contains(&expected),
                "linkme slice missing group: {expected}; saw {names:?}"
            );
        }
    }

    #[test]
    fn no_duplicate_group_names_in_slice() {
        let mut names: Vec<&str> = GROUP_DECLS.iter().map(|g| g.name).collect();
        names.sort_unstable();
        let before = names.len();
        names.dedup();
        assert_eq!(
            names.len(),
            before,
            "duplicate group display name in linkme slice",
        );
    }
}
