// `linkme`'s distributed slices use `link_section` to
// aggregate items at link time. Workspace lints `deny`
// `unsafe_code` (CLAUDE.md), so we opt this module in --
// the safety argument is that linkme is the standard Rust
// solution for cross-crate aggregation, the link-section
// usage is contained to its own machinery, and no raw
// pointer / unchecked-cast code lives here.
#![allow(unsafe_code)]

//! Option groups: the user-facing organization unit for
//! `:customize <name>` (`mode-architecture.md` §6.7.1.1).
//!
//! Each group is a unique Rust type implementing [`OptionGroup`].
//! Pre-registered built-in groups ship with the editor:
//! `Editor`, `Display`, `Editing`, `Lsp`, `Completion`, `Picker`,
//! `Filetree`, `Oil`, `Help`, `Appearance`. Plugins can join
//! existing groups (by referencing the type) or declare new
//! ones (in their own `<plugin-id>.<group>` namespace).
//!
//! Compile-time invariants enforced by the [`crate::groups!`]
//! macro:
//!
//! - Group display names cannot end in `-mode`. The
//!   modes-vs-groups disambiguation rule
//!   (`mode-architecture.md` §6.7.1) depends on this -- a name
//!   ending in `-mode` is a mode; a name not ending in `-mode`
//!   is a group. The macro emits a `const fn` byte-walk
//!   assertion at the declaration site; violations are compile
//!   errors.
//! - Within a crate, two `groups!` invocations with the same
//!   identifier are duplicate `struct` definitions ⇒ compile
//!   error.
//!
//! Cross-crate display-name uniqueness is enforced at startup
//! via [`linkme`] aggregation in [`GROUP_DECLS`].

use std::any::TypeId;

/// Compile-time declaration of one option group. Each group
/// is a unit struct (typically generated by the [`crate::groups!`]
/// macro) implementing this trait.
pub trait OptionGroup: 'static {
    /// Public display name. Used as the boundary string for
    /// `:customize <name>` and as the prefix-match key for
    /// option group queries. Cannot end in `-mode`.
    const NAME: &'static str;

    /// Doc string. Shown in `:describe-group <name>` and the
    /// `:customize` group picker.
    const DOC: &'static str;

    /// `TypeId` for type-driven group lookups.
    fn type_id() -> TypeId
    where
        Self: Sized,
    {
        TypeId::of::<Self>()
    }
}

/// Metadata captured at macro expansion for one group. Submitted
/// to the [`GROUP_DECLS`] distributed slice; the registry's
/// startup loader walks the slice to validate uniqueness and
/// build the `&str → TypeId` lookup table.
pub struct OptionGroupMetadata {
    pub name: &'static str,
    pub doc: &'static str,
    pub type_id: fn() -> TypeId,
}

impl OptionGroupMetadata {
    pub const fn for_group<G: OptionGroup>() -> Self {
        Self {
            name: G::NAME,
            doc: G::DOC,
            type_id: TypeId::of::<G>,
        }
    }
}

/// Distributed slice of every group declared anywhere in the
/// workspace. Each `groups!` macro invocation submits a
/// `&'static OptionGroupMetadata` element here. The registry
/// validates cross-crate uniqueness at startup.
#[linkme::distributed_slice]
pub static GROUP_DECLS: [&'static OptionGroupMetadata];

/// `const fn` byte-walk: returns true iff `s` ends in the
/// literal suffix `-mode`. Used by the `groups!` macro to
/// assert the disambiguation invariant at compile time.
///
/// Returns `false` for strings shorter than the suffix.
/// Implementation walks bytes from the end -- ASCII-safe
/// because mode/group names are constrained to lowercase
/// letters, digits, and hyphens.
pub const fn ends_with_mode_suffix(s: &str) -> bool {
    let bytes = s.as_bytes();
    let suffix = b"-mode";
    let n = bytes.len();
    let m = suffix.len();
    if n < m {
        return false;
    }
    let mut i = 0;
    while i < m {
        if bytes[n - m + i] != suffix[i] {
            return false;
        }
        i += 1;
    }
    true
}

